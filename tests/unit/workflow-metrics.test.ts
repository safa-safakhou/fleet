import { expect, it } from "vitest";
import { WorkflowMetrics } from "../../src/platform/workflow-metrics.js";

it("includes task queue time and does not count a legal suboptimal answer as feedback-recovery eligible", () => {
  const m = new WorkflowMetrics();
  m.record({
    id: "suboptimal",
    bindingId: "a",
    completed: true,
    factualCorrect: true,
    objectiveCorrect: false,
    firstAttemptCorrect: false,
    recovered: false,
    attempts: 3,
    corrections: 0,
    repeatedFailures: 0,
    rejectedProposals: 0,
    rejectedValidProposals: 0,
    proposalChecks: 3,
    invalidEffects: 0,
    isolationViolations: 0,
    unknownUsageCalls: 0,
    inputTokens: 100,
    outputTokens: 20,
    elapsedMs: 1000,
    queueDelayMs: 50,
    callLatencyMs: [100, 200, 300],
  });
  expect(m.snapshot()).toMatchObject({
    firstPassFailures: 1,
    recoveryEligible: 0,
    endToEndLatencyMs: { p50: 1050, p95: 1050 },
  });
});

it("keeps first attempt, recovery and full completion distinct and exposes every required denominator", () => {
  const m = new WorkflowMetrics();
  m.record({
    id: "a",
    bindingId: "a",
    completed: true,
    factualCorrect: true,
    objectiveCorrect: true,
    firstAttemptCorrect: false,
    recovered: true,
    attempts: 4,
    corrections: 1,
    repeatedFailures: 0,
    rejectedProposals: 1,
    rejectedValidProposals: 0,
    proposalChecks: 3,
    invalidEffects: 0,
    isolationViolations: 0,
    unknownUsageCalls: 0,
    inputTokens: 100,
    outputTokens: 20,
    elapsedMs: 1000,
    queueDelayMs: 50,
    callLatencyMs: [100, 200, 300, 400],
  });
  m.record({
    id: "b",
    bindingId: "b",
    completed: false,
    factualCorrect: null,
    objectiveCorrect: null,
    firstAttemptCorrect: true,
    recovered: false,
    attempts: 1,
    corrections: 0,
    repeatedFailures: 0,
    rejectedProposals: 0,
    rejectedValidProposals: 0,
    proposalChecks: 0,
    invalidEffects: 0,
    isolationViolations: 0,
    unknownUsageCalls: 1,
    inputTokens: null,
    outputTokens: null,
    elapsedMs: 2000,
    queueDelayMs: 100,
    callLatencyMs: [2000],
  });
  expect(m.snapshot()).toMatchObject({
    workflows: 2,
    completed: 1,
    firstAttemptCorrect: 1,
    recovered: 1,
    recoveryEligible: 1,
    factualCorrect: 1,
    factualGraded: 1,
    objectiveCorrect: 1,
    objectiveGraded: 1,
    attempts: 5,
    corrections: 1,
    rejectedProposals: 1,
    rejectedValidProposals: 0,
    proposalChecks: 3,
    invalidEffects: 0,
    isolationViolations: 0,
    unknownUsageCalls: 1,
    knownInputTokens: 100,
    knownOutputTokens: 20,
    unknownUsageWorkflows: 1,
    uniqueBindings: 2,
    queueDelayMs: { p50: 50, p95: 100 },
    callLatencyMs: { p50: 300, p95: 2000 },
  });
});
